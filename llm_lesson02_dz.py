########################### Few-shot ###########################
prompt = PromptTemplate.from_template("""
    Ти - досвідчений методист. Твоє завдання: створення плану навчального курсу з певної теми для цільової аудиторії.
    Вхідні параметри: тема, опис цільової аудиторії (початківці, професіонали, діти, тощо).
    Створи детальний план курсу з розподілом по модулях та урокам.  
    
    ### ПРИКЛАД 1
    ТЕМА КУРСУ
    Веб-розробка для початківців
    ОПИС ЦІЛЬОВОЇ АУДИТОРІЇ
    Початківці, які хочуть навчитися створювати веб-сайти з нуля.   
    ПЛАН КУРСУ
    Модуль 1: Вступ до веб-розробки
    Урок 1: Що таке веб-розробка?
    Урок 2: Основи HTML та CSS
    Модуль 2: JavaScript для початківців
    Урок 1: Вступ до JavaScript
    Урок 2: Основи програмування на JavaScript
    ...
    
    ### ПРИКЛАД 2
    ТЕМА КУРСУ
    Штучний Інтелект
    ОПИС ЦІЛЬОВОЇ АУДИТОРІЇ
    Діти від 10 до 15 років, які цікавляться технологіями та комп'ютерами.
    ПЛАН КУРСУ
    **Модуль 1: Що таке Штучний Інтелект (1-2 години)**
    *   **Урок 1: Що таке Штучний Інтелект (AI)?**
        *   Пояснення поняття Штучного Інтелекту: як комп'ютери навчаються та вирішують проблеми.
        *   Приклади використання Штучного Інтелекту в повсякденному житті (ігри, рекомендації, голосові помічники).
        *   Пояснення різниці між "розумним" та "автоматизованим" інтелектом.
    *   **Урок 2: Як працює Штучний Інтелект?**
        *   Простий огляд основних принципів: навчання на даних, алгоритми, машинне навчання.
        *   Пояснення концепції "машинного навчання" (Machine Learning) - як комп'ютери вчаться без явного програмування.
        *   Візуалізація: використання простих ігор, що демонструють процес навчання.
    **Модуль 2: Основи Машинного Навчання (2-3 години)**
    *   **Урок 1: Що таке Машинне Навчання?**
        *   Пояснення, що таке машинне навчання - як комп'ютери "навчаються" на даних.
        *   Приклади: фільтрація зображень, розпізнавання мови.
        *   Пояснення, що дані - це основа для навчання.
    *   **Урок 2: Типи Машинного Навчання**
        *   Навчання з учителем (Supervised Learning):  Навчання на наборі даних з правильними відповідями.
        *   Навчання без учителя (Unsupervised Learning):  Виявлення закономірностей у даних без попередніх знань.
        *   Пояснення простих прикладів:  розпізнавання кольорів, класифікація листів.
    *   **Урок 3: Практичне завдання:  Простий "гра-ігри"**
        *   Використання онлайн-інструментів (наприклад, Scratch) для створення простих ігор, де програма навчається на даних (наприклад, "Познач і перемісти").
    **Модуль 3: Застосування Штучного Інтелекту (1-2 години)**
    *   **Урок 1: Штучний Інтелект у іграх**
        *   Приклади:  ігри, де Штучний Інтелект допомагає персонажам.
        *   Пояснення, як Штучний Інтелект використовується для створення більш реалістичних ігрових персонажів.
    *   **Урок 2: Штучний Інтелект у розробці програм**
        *   Пояснення, як Штучний Інтелект допомагає розробникам автоматизувати рутинні завдання.
        *   Приклади:  автоматичне генерування коду, тестування програм.
    *   **Урок 3: Штучний Інтелект у розв'язанні проблем**
        *   Пояснення, як Штучний Інтелект може допомогти в вирішенні складних задач.
        *   Приклади:  аналіз даних, прогнозування.
    
    ### НОВИЙ ЗАПИТ
    ТЕМА КУРСУ
    {topic}
    ОПИС ЦІЛЬОВОЇ АУДИТОРІЇ
    {audience}
    """)
# створення ланцюга
chain = prompt | llm
# використання
response = chain.invoke(
    {
        "topic": "Windows для 'чайників'",
        "audience": "Початківці, які тільки починають знайомство з комп'ютерами."
    }
)
print(response)